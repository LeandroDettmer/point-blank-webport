// Plugin.Core/Enums/EventErrorEnum.cs (subset)
const ERRORS: Record<number, string> = {
  0x00000000: "SUCCESS",
  0x80000000: "FAIL",
  0x80000101: "EVENT_LOG_IN_ALREADY_LOGIN",
  0x80000102: "EVENT_LOG_IN_INVALID_ACCOUNT",
  0x80000106: "EVENT_LOG_IN_TIME_OUT_2 (access level)",
  0x80000107: "EVENT_LOG_IN_BLOCK_ACCOUNT",
  0x80000117: "LOGIN_ID_PASS_INCORRECT (token not found)",
  0x80000121: "LOGIN_BLOCK_IP",
  0x80000201: "CHANNEL_FULL",
  0x80000202: "CHANNEL_REQUIREMENT",
};

export function errorName(code: number): string {
  code >>>= 0;
  return ERRORS[code] ?? `0x${code.toString(16).padStart(8, "0")}`;
}
