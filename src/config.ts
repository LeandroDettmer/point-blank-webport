/** One entry of public/assets/maps/index.json (generated by the maps-2017 export tool). */
export interface MapIndexEntry {
  id: string;
  pack: string;
  mapId: number | null;
  mapIdSource: string | null;
  name: string;
  nameEn: string;
  source: string;
  tris: number;
  collisionTris: number;
  bounds: { min: number[]; max: number[] };
  respawns: number;
  teams: { red: number; blue: number };
  respawnSource: string;
  check: { visual: boolean; collisionGlb: boolean; respawnsInside: string; collisionInsideVisual: boolean; dMin: number[]; dMax: number[] };
}

// Populated by loadMapIndex(); until then (or if it fails) these fall back to the 4 maps this app
// shipped with before the 2017 export, so ?map= and the room map picker still work.
export const AVAILABLE_MAPS: string[] = ["metro", "nstation", "blowcity", "sewerage"];
export type MapId = string;
export let MAP_LABELS: Record<string, string> = { metro: "Metro", nstation: "M. Station", blowcity: "Blow City", sewerage: "Sewerage" };

let mapIndexById = new Map<string, MapIndexEntry>();
let mapIdToId = new Map<number, string>();
let mapIndexPromise: Promise<void> | null = null;

function passesCheck(e: MapIndexEntry): boolean {
  const c = e.check;
  if (!c?.visual || !c.collisionGlb) return false;
  const [have, want] = (c.respawnsInside ?? "0/0").split("/").map(Number);
  return have === want;
}

/** Fetches maps/index.json (the PBCross maps). Call once at boot, before the first
 * resolveMapId()/mapFromRoomMapId() that must know about a non-legacy map. Safe to call more than
 * once (idempotent); never rejects. */
export function loadMapIndex(): Promise<void> {
  if (mapIndexPromise) return mapIndexPromise;
  mapIndexPromise = fetch("/assets/maps/index.json")
    .then((r) => (r.ok ? (r.json() as Promise<MapIndexEntry[]>) : []))
    .catch(() => [] as MapIndexEntry[])
    .then((entries) => {
      const byId = new Map<string, MapIndexEntry>();
      const idToMapId = new Map<number, string>();
      const ids: string[] = [];
      const labels: Record<string, string> = {};
      for (const e of entries) {
        byId.set(e.id, e);
        if (!passesCheck(e)) continue;
        ids.push(e.id);
        labels[e.id] = e.name || e.nameEn || e.id;
        if (e.mapId != null && !idToMapId.has(e.mapId)) idToMapId.set(e.mapId, e.id); // 9 maps have no mapId: left unmapped
      }
      mapIndexById = byId;
      if (ids.length > 0) {
        mapIdToId = idToMapId;
        AVAILABLE_MAPS.length = 0;
        AVAILABLE_MAPS.push(...ids);
        MAP_LABELS = labels;
        const requested = new URLSearchParams(window.location.search).get("map")?.toLowerCase();
        if (requested && AVAILABLE_MAPS.includes(requested)) CurrentMap = requested;
      }
    });
  return mapIndexPromise;
}

/** Index metadata for a map id (name, mapId, respawn/collision check), once loadMapIndex() resolved. */
export function mapIndexEntry(id: string): MapIndexEntry | undefined {
  return mapIndexById.get(id);
}

function resolveMapId(): MapId {
  const requested = new URLSearchParams(window.location.search).get("map")?.toLowerCase();
  return requested && AVAILABLE_MAPS.includes(requested) ? requested : "nstation";
}

/** Map loaded by the next startGame(): ?map= at boot, overridable at runtime via setCurrentMap (room map). */
export let CurrentMap: MapId = resolveMapId();

export function setCurrentMap(map: MapId): void {
  CurrentMap = map;
}

/** Server room mapId (Data/Maps/Matches.xml) -> exported client map. Falls back to the pre-index
 * table (4/36) until loadMapIndex() has resolved. */
export function mapFromRoomMapId(mapId: number): MapId {
  return mapIdToId.get(mapId) ?? ({ 4: "nstation", 36: "metro" } as Record<number, MapId>)[mapId] ?? "nstation";
}

